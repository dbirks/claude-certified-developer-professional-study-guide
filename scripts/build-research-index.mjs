#!/usr/bin/env node
// Regenerate research/sources.yaml (all citations, grouped by skill) and research/coverage-matrix.md
// (skill → objective → packet → citations → quote check → chapter → fact-check).
//   node scripts/build-research-index.mjs
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { parse, stringify } from 'yaml';

const ROOT = new URL('..', import.meta.url).pathname;
const syl = readFileSync(join(ROOT, 'src/data/syllabus.ts'), 'utf8');
const domains = [...syl.matchAll(/n: (\d+),\s*slug: '([^']+)',\s*title: '([^']+)',\s*weight: (\d+),\s*skills: \[([\s\S]*?)\n    \],/g)].map((m) => ({
  n: +m[1], slug: m[2], title: m[3], weight: +m[4],
  skills: [...m[5].matchAll(/id: '([\d.]+)',(?: short: '[^']*',)? slug: '([^']+)', title: '([^']+)', priority: '(\w+)', objective: '((?:[^'\\]|\\.)*)'/g)].map((s) => ({ id: s[1], slug: s[2], title: s[3], priority: s[4], objective: s[5] })),
}));

function walk(dir) {
  return existsSync(dir) ? readdirSync(dir).flatMap((f) => { const p = join(dir, f); return statSync(p).isDirectory() ? walk(p) : [p]; }) : [];
}
const chapters = new Map();
for (const f of walk(join(ROOT, 'content')).filter((f) => f.endsWith('.mdx'))) {
  const src = readFileSync(f, 'utf8');
  const fm = parse(src.match(/^---\n([\s\S]*?)\n---/)?.[1] ?? '') ?? {};
  if (fm.kind === 'skill') {
    const words = src.replace(/^---[\s\S]*?---/, '').replace(/```[\s\S]*?```/g, '').split(/\n/).filter((l) => !/^\s*[|<]/.test(l)).join(' ').split(/\s+/).filter(Boolean).length;
    const cites = new Set([...src.matchAll(/<Cite\s+id=["']([^"']+)["']/g)].flatMap((m) => m[1].split(/[\s,]+/)));
    chapters.set(fm.skill, { path: f.replace(ROOT, ''), status: fm.status, words, cites: cites.size });
  }
}

const all = [];
const rows = [];
for (const d of domains) {
  for (const s of d.skills) {
    const cfile = join(ROOT, 'research/citations', s.slug + '.yaml');
    const cites = existsSync(cfile) ? parse(readFileSync(cfile, 'utf8')) ?? [] : [];
    for (const c of cites) all.push({ skill: s.id, slug: s.slug, ...c });
    const qfile = join(ROOT, 'research/quote-check', s.slug + '.json');
    const q = existsSync(qfile) ? JSON.parse(readFileSync(qfile, 'utf8')) : null;
    const qs = q ? `${q.filter((r) => r.status.startsWith('ok')).length}/${q.length}` : '—';
    const ch = chapters.get(s.id);
    const fc = existsSync(join(ROOT, 'research/fact-check', s.slug + '.md')) ? 'done' : '—';
    const packet = existsSync(join(ROOT, 'research/packets', s.slug + '.md')) ? 'yes' : '—';
    rows.push(`| ${s.id} | ${s.title} | ${d.weight}% | ${packet} | ${cites.length || '—'} | ${qs} | ${ch ? `[${ch.status}](../${ch.path}) · ${ch.words} words · ${ch.cites} cited` : '—'} | ${fc} |`);
  }
}

const byUrl = new Map();
for (const c of all) {
  const key = c.url.split('#')[0];
  if (!byUrl.has(key)) byUrl.set(key, { url: key, title: c.title, source: c.source, accessed: String(c.accessed), cited_by: [] });
  byUrl.get(key).cited_by.push(`${c.slug}:${c.id}`);
}
writeFileSync(join(ROOT, 'research/sources.yaml'),
  `# Generated by scripts/build-research-index.mjs — do not edit. Per-claim detail lives in research/citations/*.yaml.\n` +
  stringify([...byUrl.values()].sort((a, b) => a.url.localeCompare(b.url)), { lineWidth: 0 }));

const matrix = `# Coverage matrix

Generated by \`scripts/build-research-index.mjs\` from the syllabus, research files and content. Do not edit by hand.

Blueprint: Exam Guide v1.0 (effective November 2026), verified 2026-11-19 — see [exam-guide.md](exam-guide.md).
Columns: research packet exists · citation entries · quotes verified verbatim by \`scripts/verify-quotes.mjs\` (ok/total) · chapter status · independent fact-check log in \`research/fact-check/\`.

| ID | Skill | Domain weight | Packet | Citations | Quotes verified | Chapter | Fact-check |
|---|---|---|---|---|---|---|---|
${rows.join('\n')}

Unique source URLs: ${byUrl.size} · citation entries: ${all.length}
`;
writeFileSync(join(ROOT, 'research/coverage-matrix.md'), matrix);
// fact-check-log.md: one entry per reviewed page with reviewer(s) and the summary bullets of each pass.
const fcDir = join(ROOT, 'research/fact-check');
const fcFiles = existsSync(fcDir) ? readdirSync(fcDir).filter((f) => f.endsWith('.md')).sort() : [];
const fcEntries = fcFiles.map((f) => {
  const txt = readFileSync(join(fcDir, f), 'utf8');
  const title = (txt.match(/^# (.+)$/m) || [, f])[1].replace(/^Fact-check:\s*/, '');
  const reviewers = [...txt.matchAll(/Reviewer:\s*([^\n]+)/g)].map((m) => m[1].trim());
  const passes = (txt.match(/^## Second pass/gm) || []).length + 1;
  const summary = (txt.match(/## Summary\n([\s\S]*?)(?=\n## )/) || [, ''])[1].trim().split('\n').filter(Boolean).slice(0, 6).map((l) => (l.startsWith('-') ? l : `- ${l}`)).join('\n');
  return `### ${title}\n\nLog: [fact-check/${f}](fact-check/${f}) · passes: ${passes} · reviewer(s): ${reviewers.join('; ') || 'see log'}\n\n${summary}\n`;
});
writeFileSync(join(ROOT, 'research/fact-check-log.md'), `# Fact-check log

Generated by \`scripts/build-research-index.mjs\`. Each chapter was drafted from a source-pinned research packet, then
independently reviewed claim by claim against its cited sources by a second AI model (Gemini 4 Hydrogen via AGY, or
GPT-6.x via Codex), which edited the chapter and recorded every change. \`scripts/verify-quotes.mjs\` then re-fetched every
source and confirmed each citation's quote appears on the page (results in \`quote-check/\`). Reviewers are AI models, not
human subject-matter experts.

${fcEntries.join('\n')}`);

console.log(`fact-check log: ${fcEntries.length} entries`);
console.log(`sources: ${byUrl.size} urls, ${all.length} citations; matrix rows: ${rows.length}`);
